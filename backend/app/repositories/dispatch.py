"""backend/app/repositories/dispatch.py — Data access for dispatch recommendations and audit log."""
import sqlite3
from typing import List, Optional
from datetime import datetime, timezone
from app.schemas.dispatch import (
    DispatchRecommendation,
    DispatchRecommendationBase,
    DispatchLogEntry,
    DispatchStatus,
    RouteSource,
)

def _now_iso() -> str:
    return datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")

class DispatchRepository:
    def __init__(self, conn: sqlite3.Connection):
        self.conn = conn

    def create_recommendation(self, rec: DispatchRecommendationBase) -> DispatchRecommendation:
        now = _now_iso()
        cursor = self.conn.execute(
            """
            INSERT INTO dispatch_recommendations
            (vehicle_id, source_stop_id, destination_stop_id, estimated_arrival_minutes,
             estimated_distance_km, useful_capacity, priority_score, reason, route_source, status, created_at)
            VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)
            """,
            (
                rec.vehicle_id,
                rec.source_stop_id,
                rec.destination_stop_id,
                rec.estimated_arrival_minutes,
                rec.estimated_distance_km,
                rec.useful_capacity,
                rec.priority_score,
                rec.reason,
                rec.route_source,
                rec.status,
                now,
            ),
        )
        rec_id = cursor.lastrowid

        # Log creation
        self.create_log(
            rec_id=rec_id,
            vehicle_id=rec.vehicle_id,
            action="proposed",
            previous_state=None,
            new_state="proposed",
            notes="Recommendation generated by dispatch engine",
        )
        self.conn.commit()
        return self.get_by_id(rec_id)

    def get_all(self, status: Optional[DispatchStatus] = None) -> List[DispatchRecommendation]:
        query = """
            SELECT r.*,
                   v.vehicle_code,
                   s1.name as source_stop_name,
                   s2.name as destination_stop_name
            FROM dispatch_recommendations r
            JOIN vehicles v ON r.vehicle_id = v.id
            JOIN stops s1 ON r.source_stop_id = s1.id
            JOIN stops s2 ON r.destination_stop_id = s2.id
        """
        params = []
        if status:
            query += " WHERE r.status = ?"
            params.append(status)
        query += " ORDER BY r.id DESC"

        cursor = self.conn.execute(query, params)
        rows = cursor.fetchall()
        return [self._map_row(r) for r in rows]

    def get_by_id(self, rec_id: int) -> Optional[DispatchRecommendation]:
        query = """
            SELECT r.*,
                   v.vehicle_code,
                   s1.name as source_stop_name,
                   s2.name as destination_stop_name
            FROM dispatch_recommendations r
            JOIN vehicles v ON r.vehicle_id = v.id
            JOIN stops s1 ON r.source_stop_id = s1.id
            JOIN stops s2 ON r.destination_stop_id = s2.id
            WHERE r.id = ?
        """
        cursor = self.conn.execute(query, (rec_id,))
        r = cursor.fetchone()
        if not r:
            return None
        return self._map_row(r)

    def update_status(
        self, rec_id: int, new_status: DispatchStatus, reviewed_by: Optional[str] = None, notes: Optional[str] = None
    ) -> Optional[DispatchRecommendation]:
        rec = self.get_by_id(rec_id)
        if not rec:
            return None

        old_status = rec.status
        now = _now_iso()

        self.conn.execute(
            """
            UPDATE dispatch_recommendations
            SET status = ?, reviewed_at = ?, reviewed_by = ?
            WHERE id = ?
            """,
            (new_status, now, reviewed_by or "dispatcher", rec_id),
        )

        # Log transition
        self.create_log(
            rec_id=rec_id,
            vehicle_id=rec.vehicle_id,
            action=new_status,
            previous_state=old_status,
            new_state=new_status,
            notes=notes,
        )

        # If approved, update vehicle status to 'assigned'
        if new_status == "approved":
            self.conn.execute(
                "UPDATE vehicles SET status = 'assigned', updated_at = ? WHERE id = ?",
                (now, rec.vehicle_id),
            )
        elif new_status in ("rejected", "cancelled") and old_status == "approved":
            # Revert vehicle status back to available
            self.conn.execute(
                "UPDATE vehicles SET status = 'available', updated_at = ? WHERE id = ?",
                (now, rec.vehicle_id),
            )

        self.conn.commit()
        return self.get_by_id(rec_id)

    def create_log(
        self,
        rec_id: int,
        vehicle_id: int,
        action: str,
        previous_state: Optional[str],
        new_state: Optional[str],
        notes: Optional[str],
    ) -> None:
        now = _now_iso()
        self.conn.execute(
            """
            INSERT INTO dispatch_log
            (recommendation_id, vehicle_id, action, previous_state, new_state, notes, created_at)
            VALUES (?, ?, ?, ?, ?, ?, ?)
            """,
            (rec_id, vehicle_id, action, previous_state, new_state, notes, now),
        )

    def get_logs(self, limit: int = 50) -> List[DispatchLogEntry]:
        query = """
            SELECT l.*, v.vehicle_code
            FROM dispatch_log l
            JOIN vehicles v ON l.vehicle_id = v.id
            ORDER BY l.id DESC
            LIMIT ?
        """
        cursor = self.conn.execute(query, (limit,))
        rows = cursor.fetchall()
        return [
            DispatchLogEntry(
                id=r["id"],
                recommendation_id=r["recommendation_id"],
                vehicle_id=r["vehicle_id"],
                vehicle_code=r["vehicle_code"],
                action=r["action"],
                previous_state=r["previous_state"],
                new_state=r["new_state"],
                notes=r["notes"],
                created_at=r["created_at"],
            )
            for r in rows
        ]

    def has_active_approval(self, vehicle_id: int) -> bool:
        cursor = self.conn.execute(
            "SELECT 1 FROM dispatch_recommendations WHERE vehicle_id = ? AND status = 'approved'",
            (vehicle_id,),
        )
        return cursor.fetchone() is not None

    def _map_row(self, r: sqlite3.Row) -> DispatchRecommendation:
        return DispatchRecommendation(
            id=r["id"],
            vehicle_id=r["vehicle_id"],
            vehicle_code=r["vehicle_code"],
            source_stop_id=r["source_stop_id"],
            source_stop_name=r["source_stop_name"],
            destination_stop_id=r["destination_stop_id"],
            destination_stop_name=r["destination_stop_name"],
            estimated_arrival_minutes=r["estimated_arrival_minutes"],
            estimated_distance_km=r["estimated_distance_km"],
            useful_capacity=r["useful_capacity"],
            priority_score=r["priority_score"],
            reason=r["reason"],
            route_source=r["route_source"] or "unknown",
            status=r["status"],
            created_at=r["created_at"],
            reviewed_at=r["reviewed_at"],
            reviewed_by=r["reviewed_by"],
            route_geometry=None,
            impact=None,
        )

